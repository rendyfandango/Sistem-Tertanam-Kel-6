#include "oled_ssd1306.h"
#include "esp_log.h"

static const char *TAG = "OLED";

// Fungsi untuk mengaktifkan pin I2C di ESP32-S3
void i2c_master_init(void) {
    i2c_config_t conf = {
        .mode = I2C_MODE_MASTER,
        .sda_io_num = I2C_MASTER_SDA_IO,
        .scl_io_num = I2C_MASTER_SCL_IO,
        .sda_pullup_en = GPIO_PULLUP_ENABLE,
        .scl_pullup_en = GPIO_PULLUP_ENABLE,
        .master.clk_speed = I2C_MASTER_FREQ_HZ,
    };
    i2c_param_config(I2C_MASTER_NUM, &conf);
    i2c_driver_install(I2C_MASTER_NUM, conf.mode, 0, 0, 0);
    ESP_LOGI(TAG, "I2C berhasil diinisialisasi");
}

// Fungsi untuk menyalakan OLED
void ssd1306_init(void) {
    // Urutan perintah standar untuk menyalakan SSD1306
    uint8_t init_cmds[] = {
        0xAE, 0x20, 0x00, 0xC8, 0x00, 0x10, 0x40, 0x81, 
        0xFF, 0xA1, 0xA6, 0xA8, 0x3F, 0xA4, 0xD3, 0x00, 
        0xD5, 0xF0, 0xD9, 0x22, 0xDA, 0x12, 0xDB, 0x20, 
        0x8D, 0x14, 0xAF 
    };

    i2c_cmd_handle_t cmd = i2c_cmd_link_create();
    i2c_master_start(cmd);
    // Mengirim alamat OLED dengan mode Write
    i2c_master_write_byte(cmd, (OLED_I2C_ADDRESS << 1) | I2C_MASTER_WRITE, true);
    // 0x00 menandakan byte berikutnya adalah Command (Perintah)
    i2c_master_write_byte(cmd, 0x00, true); 
    i2c_master_write(cmd, init_cmds, sizeof(init_cmds), true);
    i2c_master_stop(cmd);
    
    i2c_master_cmd_begin(I2C_MASTER_NUM, cmd, 1000 / portTICK_PERIOD_MS);
    i2c_cmd_link_delete(cmd);
    
    ESP_LOGI(TAG, "OLED berhasil diinisialisasi");
}

