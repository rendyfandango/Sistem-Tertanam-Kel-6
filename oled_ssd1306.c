// --- FUNGSI HELPER I2C ---
void ssd1306_send_cmd(uint8_t cmd_data) {
    i2c_cmd_handle_t cmd = i2c_cmd_link_create();
    i2c_master_start(cmd);
    i2c_master_write_byte(cmd, (OLED_I2C_ADDRESS << 1) | I2C_MASTER_WRITE, true);
    i2c_master_write_byte(cmd, 0x00, true); // 0x00 artinya perintah (Command)
    i2c_master_write_byte(cmd, cmd_data, true);
    i2c_master_stop(cmd);
    i2c_master_cmd_begin(I2C_MASTER_NUM, cmd, 1000 / portTICK_PERIOD_MS);
    i2c_cmd_link_delete(cmd);
}

void ssd1306_send_data(uint8_t *data, uint16_t len) {
    i2c_cmd_handle_t cmd = i2c_cmd_link_create();
    i2c_master_start(cmd);
    i2c_master_write_byte(cmd, (OLED_I2C_ADDRESS << 1) | I2C_MASTER_WRITE, true);
    i2c_master_write_byte(cmd, 0x40, true); // 0x40 artinya Data Pixel
    i2c_master_write(cmd, data, len, true);
    i2c_master_stop(cmd);
    i2c_master_cmd_begin(I2C_MASTER_NUM, cmd, 1000 / portTICK_PERIOD_MS);
    i2c_cmd_link_delete(cmd);
}

// --- FUNGSI MENGGAMBAR ---
// Membersihkan layar dari memori acak (semut)
void ssd1306_clear(void) {
    uint8_t empty_row[128] = {0};
    for (uint8_t i = 0; i < 8; i++) {
        ssd1306_send_cmd(0xB0 + i); // Set baris (Page 0-7)
        ssd1306_send_cmd(0x00);     // Set kolom bawah
        ssd1306_send_cmd(0x10);     // Set kolom atas
        ssd1306_send_data(empty_row, 128); // Timpa 128 pixel dengan nol (mati)
    }
}

// Menulis teks ke koordinat tertentu
void ssd1306_draw_text(uint8_t page, uint8_t col, const char *text) {
    ssd1306_send_cmd(0xB0 + page);
    ssd1306_send_cmd(0x00 | (col & 0x0F));
    ssd1306_send_cmd(0x10 | ((col >> 4) & 0x0F));
    
    while (*text) {
        if (*text >= 32 && *text <= 126) { // Pastikan karakter ada di tabel font
            uint8_t char_data[5];
            for(int i=0; i<5; i++) char_data[i] = font5x8[*text - 32][i];
            ssd1306_send_data(char_data, 5); // Tulis huruf
            
            uint8_t space = 0x00;
            ssd1306_send_data(&space, 1); // Tambah 1 pixel spasi antar huruf
        }
        text++;
    }
}